import fs from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href);
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5331');
console.log({title:await page.title(),heading:await page.getByRole('heading',{level:1}).allTextContents(),errors});
await page.screenshot({path:process.env.F01_SCREENSHOT_PATH,fullPage:true});
await browser.close();
