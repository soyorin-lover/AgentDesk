// Run once against a fresh F03 fixture before browser mutation.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { randomUUID } from 'node:crypto';
const connectionPath = process.argv[2];
if (!connectionPath) throw Error('connection.json path required');
const c = JSON.parse(await readFile(connectionPath, 'utf8'));
const { ApiClient } = await import(pathToFileURL(join(c.backendSnapshot.path, 'src/client/api.ts')).href);
const token = await readFile(c.tokenFile, 'utf8');
const api = new ApiClient({baseUrl:c.url,getToken:()=>token});
const p=c.projectId;
const key=()=>randomUUID();
const wait=async(fn:()=>Promise<any>, ok:(x:any)=>boolean)=>{ const end=Date.now()+30000; while(Date.now()<end){const x=await fn();if(ok(x))return x;await new Promise(r=>setTimeout(r,60));}throw Error('poll timeout');};
const reject=async(fn:()=>Promise<any>,code:string)=>assert.rejects(fn,new RegExp(code));
const view=()=>api.workflow(p);
const version=async()=>({expectedVersion:(await view()).version});
const tv=async(id:string)=>({expectedVersion:(await api.task(id)).task.version});
const binding=(await api.executionBinding(p)).binding;
assert.ok(binding);
const executionBinding={id:binding.id,revision:binding.revision,grantId:binding.grantId,baselineCommit:binding.baselineCommit};
const node=(id:string,dependencyIds:string[]=[],parentId?:string)=>({id,name:id,goal:'F03 deterministic sample change',acceptanceCriteria:['Only owned sample.txt changes'],roleId:'dev',memberId:'member',agentInstanceId:'codex-local',dependencyIds,executionBinding,...(parentId?{parentId}:{})});
const draft={roles:[{id:'dev',name:'Developer',responsibility:'Implement sample',defaultAgentInstanceId:'codex-local'}],members:[{id:'member',name:'Fixture agent',roleId:'dev',agentInstanceId:'codex-local'}],ownerMemberId:'member',nodes:[node('a'),node('b',['a'],'a')]};
assert.equal((await view()).version,0);
await reject(()=>api.saveWorkflow(p,{...draft,expectedVersion:0,nodes:[node('a',['b']),node('b',['a'])]},key()),'workflow_cycle');
await reject(()=>api.saveWorkflow(p,{...draft,expectedVersion:0,nodes:[node('a',[],'b'),node('b',[],'a')]},key()),'workflow_cycle');
await reject(()=>api.saveWorkflow(p,{...draft,expectedVersion:0,nodes:[node('a',['missing'])]},key()),'workflow_invalid_reference');
await api.saveWorkflow(p,{...draft,expectedVersion:0},key());
await reject(async()=>api.linkWorkflowTask(p,{...await version(),revision:1,nodeId:'a'},key()),'workflow_not_approved');
await reject(async()=>api.approveWorkflow(p,{...await version(),revision:1,nodeIds:['b']},key()),'approval_dependencies_missing');
await api.approveWorkflow(p,{...await version(),revision:1,nodeIds:['a','b']},key());
assert.equal((await api.tasks(0,50,undefined,{projectId:p})).items.length,0);
const a=await api.linkWorkflowTask(p,{...await version(),revision:1,nodeId:'a'},key());
const b=await api.linkWorkflowTask(p,{...await version(),revision:1,nodeId:'b'},key());
assert.equal((await api.task(a.id)).workspace.status,'unprepared');
await reject(async()=>api.prepareWorkspace(b.id,await tv(b.id),key()),'workflow_dependencies_blocked');
await api.prepareWorkspace(a.id,await tv(a.id),key());
await wait(()=>api.task(a.id),d=>d.workspace.status==='ready');
const run=await api.startRun(a.id,await tv(a.id),key());
await wait(()=>api.run(run.id),r=>r.status==='succeeded');
assert.equal((await view()).nodeStates.find((n:any)=>n.nodeId==='a').status,'awaiting_confirmation');
const snapshot=await api.snapshot(a.id,await tv(a.id),key());
const check=await api.startCheck(a.id,{...await tv(a.id),presetId:'sample-pass',snapshotId:snapshot.id},key());
await wait(()=>api.checks(a.id),r=>r.items.some((x:any)=>x.id===check.id&&x.status==='passed'));
await api.accept(a.id,{...await tv(a.id),snapshotId:snapshot.id},key());
const acceptance=(await api.acceptance(a.id)).acceptance;
assert.equal((await view()).nodeStates.find((n:any)=>n.nodeId==='a').status,'awaiting_confirmation');
await reject(async()=>api.prepareWorkspace(b.id,await tv(b.id),key()),'workflow_dependencies_blocked');
await api.confirmWorkflowNode(p,{...await version(),revision:1,nodeId:'a',acceptanceId:acceptance.id},key());
assert.equal((await view()).nodeStates.find((n:any)=>n.nodeId==='a').status,'completed');
await api.prepareWorkspace(b.id,await tv(b.id),key());
await wait(()=>api.task(b.id),d=>d.workspace.status==='ready');
const feedback=await api.startRun(a.id,{...await tv(a.id),input:'Explicit fixture feedback invalidates previous acceptance'},key());
await wait(()=>api.run(feedback.id),r=>r.status==='succeeded');
assert.equal((await view()).nodeStates.find((n:any)=>n.nodeId==='b').status,'blocked');
await reject(async()=>api.startRun(b.id,await tv(b.id),key()),'workflow_dependencies_blocked');
const changed=await api.saveWorkflow(p,{...draft,...await version(),nodes:draft.nodes.map(n=>({...n,name:n.name+' edited'}))},key());
assert.deepEqual([...changed.authorizationInvalidatedNodeIds].sort(),['a','b']);
await reject(async()=>api.startRun(a.id,await tv(a.id),key()),'workflow_revision_stale');
assert.equal((await api.task(a.id)).task.flow.revision,1);
assert.ok((await api.events(a.id)).items.length>0);
assert.equal((await api.workflowRevisions(p)).items.length,2);
const evidence={passed:true,at:new Date().toISOString(),connectionPath,projectId:p,taskIds:[a.id,b.id],runIds:[run.id,feedback.id],checkId:check.id,snapshotId:snapshot.id,finalRevision:2,checks:['tree cycle','DAG cycle','dangling dependency','unapproved rejected','approval closure','approval does not execute','link prepare run','real Node check','accept is not confirmation','manual confirmation unlocks','feedback blocks successor','edit revokes approvals','old task history readable']};
await writeFile(join(c.root,'http-check-evidence.json'),JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence,null,2));
